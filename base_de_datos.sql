

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    email_verified_at TIMESTAMPTZ NULL,
    remember_token VARCHAR(100) NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE doctors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NULL UNIQUE REFERENCES users(id) ON DELETE RESTRICT,
    first_names VARCHAR(150) NOT NULL,
    last_names VARCHAR(150) NOT NULL,
    professional_license VARCHAR(70) NOT NULL UNIQUE,
    specialty VARCHAR(150) NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE patients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_names VARCHAR(150) NOT NULL,
    last_names VARCHAR(150) NOT NULL,
    document_type VARCHAR(20) NULL,
    document_number VARCHAR(60) NULL,
    birth_date DATE NULL,
    phone VARCHAR(40) NULL,
    email VARCHAR(255) NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_patient_document UNIQUE(document_type, document_number),
    CONSTRAINT ck_patient_document_pair CHECK ((document_type IS NULL) = (document_number IS NULL))
);

CREATE TABLE appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL REFERENCES patients(id) ON DELETE RESTRICT,
    doctor_id BIGINT NOT NULL REFERENCES doctors(id) ON DELETE RESTRICT,
    created_by_user_id BIGINT NULL REFERENCES users(id) ON DELETE RESTRICT,
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'pending',
    reason TEXT NULL,
    cancellation_reason TEXT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_appointment_patient_doctor UNIQUE(id, patient_id, doctor_id),
    CONSTRAINT ck_appointment_interval CHECK(ends_at > starts_at),
    CONSTRAINT ck_appointment_status CHECK(status IN ('pending','confirmed','checked_in','completed','cancelled','no_show'))
);

CREATE TABLE appointment_reschedules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT NOT NULL REFERENCES appointments(id) ON DELETE RESTRICT,
    changed_by_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    previous_start TIMESTAMPTZ NOT NULL,
    previous_end TIMESTAMPTZ NOT NULL,
    new_start TIMESTAMPTZ NOT NULL,
    new_end TIMESTAMPTZ NOT NULL,
    reason TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_reschedule_previous CHECK(previous_end > previous_start),
    CONSTRAINT ck_reschedule_new CHECK(new_end > new_start),
    CONSTRAINT ck_reschedule_changed CHECK(previous_start <> new_start OR previous_end <> new_end)
);

CREATE TABLE medical_consultations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL REFERENCES patients(id) ON DELETE RESTRICT,
    doctor_id BIGINT NOT NULL REFERENCES doctors(id) ON DELETE RESTRICT,
    appointment_id BIGINT NULL UNIQUE,
    occurred_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(15) NOT NULL DEFAULT 'draft',
    chief_complaint TEXT NULL,
    subjective TEXT NULL,
    objective TEXT NULL,
    assessment TEXT NULL,
    plan TEXT NULL,
    signed_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_consultation_patient UNIQUE(id, patient_id),
    CONSTRAINT fk_consultation_appointment_match FOREIGN KEY(appointment_id, patient_id, doctor_id)
        REFERENCES appointments(id, patient_id, doctor_id) ON DELETE RESTRICT,
    CONSTRAINT ck_consultation_status CHECK(status IN ('draft','signed')),
    CONSTRAINT ck_consultation_signature CHECK(
       (status='draft' AND signed_at IS NULL)
       OR (status='signed' AND signed_at IS NOT NULL AND chief_complaint IS NOT NULL)
    ),
    CONSTRAINT ck_consultation_signed_later CHECK(signed_at IS NULL OR signed_at >= occurred_at)
);

CREATE TABLE clinical_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL UNIQUE REFERENCES patients(id) ON DELETE RESTRICT,
    opened_from_consultation_id BIGINT NOT NULL UNIQUE,
    opened_at TIMESTAMPTZ NOT NULL,
    medical_history TEXT NULL,
    surgical_history TEXT NULL,
    family_history TEXT NULL,
    social_history TEXT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_record_opening_patient_match FOREIGN KEY(opened_from_consultation_id, patient_id)
        REFERENCES medical_consultations(id, patient_id) ON DELETE RESTRICT
);

CREATE TABLE care_episodes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinical_record_id BIGINT NOT NULL REFERENCES clinical_records(id) ON DELETE RESTRICT,
    opening_consultation_id BIGINT NOT NULL REFERENCES medical_consultations(id) ON DELETE RESTRICT,
    title VARCHAR(180) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'active',
    opened_at TIMESTAMPTZ NOT NULL,
    closed_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_episode_status CHECK(status IN ('active','resolved','suspended')),
    CONSTRAINT ck_episode_closed_after_open CHECK(closed_at IS NULL OR closed_at >= opened_at)
);

CREATE TABLE episode_consultations (
    episode_id BIGINT NOT NULL REFERENCES care_episodes(id) ON DELETE RESTRICT,
    consultation_id BIGINT NOT NULL REFERENCES medical_consultations(id) ON DELETE RESTRICT,
    relation_type VARCHAR(20) NOT NULL DEFAULT 'related',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY(episode_id, consultation_id),
    CONSTRAINT ck_episode_consultation_relation CHECK(relation_type IN ('initial','follow_up','related'))
);

CREATE TABLE follow_up_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    originating_consultation_id BIGINT NOT NULL REFERENCES medical_consultations(id) ON DELETE RESTRICT,
    episode_id BIGINT NULL REFERENCES care_episodes(id) ON DELETE RESTRICT,
    appointment_id BIGINT NULL REFERENCES appointments(id) ON DELETE RESTRICT,
    resulting_consultation_id BIGINT NULL UNIQUE REFERENCES medical_consultations(id) ON DELETE RESTRICT,
    due_at TIMESTAMPTZ NULL,
    goal TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'pending',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_followup_status CHECK(status IN ('pending','scheduled','completed','cancelled','missed')),
    CONSTRAINT ck_followup_result CHECK(resulting_consultation_id IS NULL OR status = 'completed')
);

CREATE TABLE patient_conditions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL REFERENCES patients(id) ON DELETE RESTRICT,
    code_system VARCHAR(70) NULL,
    code VARCHAR(70) NULL,
    display VARCHAR(255) NOT NULL,
    clinical_status VARCHAR(20) NOT NULL DEFAULT 'active',
    verification_status VARCHAR(20) NOT NULL DEFAULT 'unconfirmed',
    onset_date DATE NULL,
    resolved_date DATE NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_condition_status CHECK(clinical_status IN ('active','resolved','inactive')),
    CONSTRAINT ck_condition_verification CHECK(verification_status IN ('unconfirmed','confirmed','refuted')),
    CONSTRAINT ck_condition_dates CHECK(onset_date IS NULL OR resolved_date IS NULL OR resolved_date >= onset_date)
);

CREATE TABLE patient_allergies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL REFERENCES patients(id) ON DELETE RESTRICT,
    substance VARCHAR(180) NOT NULL,
    reaction VARCHAR(180) NULL,
    severity VARCHAR(15) NULL,
    verification_status VARCHAR(20) NOT NULL DEFAULT 'unconfirmed',
    clinical_status VARCHAR(20) NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_allergy_severity CHECK(severity IS NULL OR severity IN ('mild','moderate','severe')),
    CONSTRAINT ck_allergy_verification CHECK(verification_status IN ('unconfirmed','confirmed','refuted')),
    CONSTRAINT ck_allergy_status CHECK(clinical_status IN ('active','inactive','resolved'))
);

CREATE TABLE patient_medications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL REFERENCES patients(id) ON DELETE RESTRICT,
    medication_name VARCHAR(180) NOT NULL,
    dose VARCHAR(100) NULL,
    frequency VARCHAR(100) NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'active',
    source VARCHAR(30) NOT NULL DEFAULT 'patient_report',
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_patient_medication_status CHECK(status IN ('active','stopped','unknown')),
    CONSTRAINT ck_patient_medication_source CHECK(source IN ('patient_report','external_prescription','internal_reconciliation'))
);

CREATE TABLE episode_conditions (
    episode_id BIGINT NOT NULL REFERENCES care_episodes(id) ON DELETE RESTRICT,
    condition_id BIGINT NOT NULL REFERENCES patient_conditions(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY(episode_id, condition_id)
);

CREATE TABLE consultation_diagnoses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consultation_id BIGINT NOT NULL REFERENCES medical_consultations(id) ON DELETE RESTRICT,
    patient_condition_id BIGINT NULL REFERENCES patient_conditions(id) ON DELETE RESTRICT,
    code_system VARCHAR(70) NULL,
    code VARCHAR(70) NULL,
    diagnosis_text VARCHAR(255) NOT NULL,
    certainty VARCHAR(20) NOT NULL DEFAULT 'suspected',
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_diagnosis_certainty CHECK(certainty IN ('suspected','confirmed','ruled_out'))
);

CREATE TABLE clinical_observations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consultation_id BIGINT NOT NULL REFERENCES medical_consultations(id) ON DELETE RESTRICT,
    code VARCHAR(70) NOT NULL,
    value_number NUMERIC(12,3) NULL,
    value_text VARCHAR(255) NULL,
    unit_code VARCHAR(32) NULL,
    observed_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_observation_has_one_value CHECK((value_number IS NOT NULL) <> (value_text IS NOT NULL))
);

CREATE TABLE prescriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consultation_id BIGINT NOT NULL REFERENCES medical_consultations(id) ON DELETE RESTRICT,
    supersedes_prescription_id BIGINT NULL REFERENCES prescriptions(id) ON DELETE RESTRICT,
    status VARCHAR(20) NOT NULL DEFAULT 'draft',
    issued_at TIMESTAMPTZ NULL,
    notes TEXT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_prescription_status CHECK(status IN ('draft','issued','replaced','void')),
    CONSTRAINT ck_prescription_issued CHECK(status = 'draft' OR issued_at IS NOT NULL),
    CONSTRAINT ck_prescription_no_self_supersede CHECK(supersedes_prescription_id IS NULL OR supersedes_prescription_id <> id)
);

CREATE TABLE prescription_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prescription_id BIGINT NOT NULL REFERENCES prescriptions(id) ON DELETE RESTRICT,
    medication_name VARCHAR(180) NOT NULL,
    dose VARCHAR(100) NOT NULL,
    route VARCHAR(100) NOT NULL,
    frequency VARCHAR(100) NOT NULL,
    duration_days INTEGER NULL,
    quantity NUMERIC(12,2) NULL,
    instructions TEXT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_prescription_duration CHECK(duration_days IS NULL OR duration_days > 0),
    CONSTRAINT ck_prescription_quantity CHECK(quantity IS NULL OR quantity > 0)
);

CREATE TABLE clinical_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consultation_id BIGINT NOT NULL REFERENCES medical_consultations(id) ON DELETE RESTRICT,
    order_type VARCHAR(20) NOT NULL,
    title VARCHAR(180) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ordered',
    priority VARCHAR(20) NOT NULL DEFAULT 'routine',
    ordered_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_order_type CHECK(order_type IN ('lab','imaging','procedure','other')),
    CONSTRAINT ck_order_status CHECK(status IN ('ordered','completed','cancelled')),
    CONSTRAINT ck_order_priority CHECK(priority IN ('routine','urgent'))
);

CREATE TABLE diagnostic_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinical_order_id BIGINT NOT NULL REFERENCES clinical_orders(id) ON DELETE RESTRICT,
    reviewed_by_user_id BIGINT NULL REFERENCES users(id) ON DELETE RESTRICT,
    status VARCHAR(20) NOT NULL DEFAULT 'received',
    interpretation TEXT NULL,
    issued_at TIMESTAMPTZ NULL,
    reviewed_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_report_status CHECK(status IN ('received','reviewed','amended')),
    CONSTRAINT ck_report_review CHECK(
       (status='received' AND reviewed_at IS NULL AND reviewed_by_user_id IS NULL)
       OR (status IN ('reviewed','amended') AND reviewed_at IS NOT NULL AND reviewed_by_user_id IS NOT NULL)
    )
);

CREATE TABLE diagnostic_result_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    diagnostic_report_id BIGINT NOT NULL REFERENCES diagnostic_reports(id) ON DELETE RESTRICT,
    test_code VARCHAR(70) NULL,
    test_name VARCHAR(180) NOT NULL,
    result_number NUMERIC(12,3) NULL,
    result_text VARCHAR(255) NULL,
    unit_code VARCHAR(32) NULL,
    reference_range VARCHAR(100) NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_result_value CHECK((result_number IS NOT NULL) <> (result_text IS NOT NULL))
);

CREATE TABLE referrals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consultation_id BIGINT NOT NULL REFERENCES medical_consultations(id) ON DELETE RESTRICT,
    specialty_or_service VARCHAR(180) NOT NULL,
    reason TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'requested',
    requested_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_referral_status CHECK(status IN ('requested','accepted','completed','cancelled'))
);

CREATE TABLE clinical_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL REFERENCES patients(id) ON DELETE RESTRICT,
    consultation_id BIGINT NULL REFERENCES medical_consultations(id) ON DELETE RESTRICT,
    uploaded_by_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    document_type VARCHAR(60) NOT NULL,
    storage_path VARCHAR(500) NOT NULL,
    mime_type VARCHAR(120) NOT NULL,
    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE care_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    episode_id BIGINT NOT NULL REFERENCES care_episodes(id) ON DELETE RESTRICT,
    created_from_consultation_id BIGINT NOT NULL REFERENCES medical_consultations(id) ON DELETE RESTRICT,
    status VARCHAR(20) NOT NULL DEFAULT 'active',
    objective TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_care_plan_status CHECK(status IN ('active','completed','cancelled'))
);

CREATE TABLE care_plan_activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    care_plan_id BIGINT NOT NULL REFERENCES care_plans(id) ON DELETE RESTRICT,
    description TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'pending',
    due_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_care_activity_status CHECK(status IN ('pending','done','cancelled'))
);

CREATE TABLE consultation_amendments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consultation_id BIGINT NOT NULL REFERENCES medical_consultations(id) ON DELETE RESTRICT,
    author_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    reason TEXT NOT NULL,
    additional_note TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT NULL REFERENCES users(id) ON DELETE RESTRICT,
    entity_name VARCHAR(100) NOT NULL,
    entity_id BIGINT NOT NULL,
    operation VARCHAR(12) NOT NULL,
    changed_fields JSONB NOT NULL DEFAULT '{}'::jsonb,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_audit_operation CHECK(operation IN ('INSERT','UPDATE','DELETE','SIGN','AMEND')),
    CONSTRAINT ck_audit_metadata_object CHECK(jsonb_typeof(changed_fields) = 'object')
);

